def get(path: str, token: str = "user_token") -> list[str]:
    query = "" if "?" in path else "?page=1&size=20&search="
    return ["", f"GET {{{{base_url}}}}{path}{query}", f"Authorization: Bearer {{{{{token}}}}}", "HTTP 200"]


def post(path: str, body: str, token: str = "user_token", status: str = "201",
         captures: list[str] | None = None, extra_asserts: list[str] | None = None) -> list[str]:
    block = ["", f"POST {{{{base_url}}}}{path}", f"Authorization: Bearer {{{{{token}}}}}",
             "Content-Type: application/json", "", body, f"HTTP {status}"]
    if captures:
        block += ["[Captures]"] + captures
    if extra_asserts:
        block += ["[Asserts]"] + extra_asserts
    return block


def put(path: str, body: str, token: str = "user_token", status: str = "200") -> list[str]:
    return ["", f"PUT {{{{base_url}}}}{path}", f"Authorization: Bearer {{{{{token}}}}}",
            "Content-Type: application/json", "", body, f"HTTP {status}"]


def delete(path: str, token: str = "admin_token", status: str = "200") -> list[str]:
    return ["", f"DELETE {{{{base_url}}}}{path}", f"Authorization: Bearer {{{{{token}}}}}", f"HTTP {status}"]


