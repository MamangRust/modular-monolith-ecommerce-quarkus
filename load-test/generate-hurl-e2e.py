def invalid_id(method: str, path: str, token: str, body: str | None = None) -> list[str]:
    block = ["", f"{method} {{{{base_url}}}}{path}", f"Authorization: Bearer {{{{{token}}}}}"]
    if body is not None:
        block += ["Content-Type: application/json", "", body]
    block += ["HTTP 400", "[Asserts]", 'jsonpath "$.status" == "error"',
              'jsonpath "$.message" contains "positive integer"']
    return block


