# Locks the Fase 2 guard contract: every ID-consuming gRPC handler guards
# id <= 0 (IdValidator) and the gateway maps gRPC INVALID_ARGUMENT -> 400
# (GrpcExceptionMapper). Asserts both the HTTP status and the error body.
